/**
 * Dropsea — Postgres schema.
 *
 * Dropsea stores no bytes: an item points at an Oxy Files asset by id. What it
 * keeps beside the id is what a page of photos needs without a call per photo
 * (size, mime, seed colours, capture time), copied when the item is added.
 *
 * `generatedId()`/`createdAt()`/`updatedAt()` from `@oxy.so/db`, snake_case
 * columns through `DATABASE_CASING`, and a real foreign key with an explicit
 * `ON DELETE` for every relation, as in Willo and Mention.
 */

import { type SQL, sql } from 'drizzle-orm';
import { check, index, integer, pgTable, text, unique } from 'drizzle-orm/pg-core';
import { createdAt, generatedId, timestamptz, updatedAt } from '@oxy.so/db';

/**
 * `albums` — a person's named collection. `owner_user_id` is the Oxy user id;
 * Dropsea has no users table of its own.
 *
 * `cover_item_id` names one of the album's own items. It carries no foreign
 * key (the two tables would reference each other); `albums.service.ts` checks
 * it belongs to the album when it is set and clears it in the same
 * transaction that removes that item. A null cover means "the newest item",
 * which the API resolves, so a fresh album needs no write to have one.
 */
export const albums = pgTable(
  'albums',
  {
    id: generatedId(),
    ownerUserId: text().notNull(),
    name: text().notNull(),
    coverItemId: text(),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    index('albums_owner_user_id_idx').on(t.ownerUserId, t.createdAt),
    check('albums_name_length_check', sql`char_length(${t.name}) between 1 and 200`),
  ],
);

/**
 * `album_items` — one asset in one album. The same asset in two albums is two
 * rows; the same asset twice in one album is refused (`unique` below), so
 * adding a batch again is idempotent.
 *
 * `seeds` are `#rrggbb` strings, best first (`@oxy.so/bloom/color-engine`).
 * `taken_at` is the photo's EXIF `DateTimeOriginal` when it has one: Oxy Files
 * does not keep a capture time.
 */
export const albumItems = pgTable(
  'album_items',
  {
    id: generatedId(),
    albumId: text()
      .notNull()
      .references(() => albums.id, { onDelete: 'cascade' }),
    assetId: text().notNull(),
    mime: text().notNull(),
    width: integer().notNull(),
    height: integer().notNull(),
    seeds: text().array().notNull().default(sql`'{}'::text[]`),
    takenAt: timestamptz(),
    addedAt: createdAt(),
  },
  (t) => [
    unique('album_items_album_asset_unique').on(t.albumId, t.assetId),
    // The page query: an album's items, newest first. Ids are uuidv7, ordered
    // by when the row was made, so the id alone is the cursor.
    index('album_items_album_id_idx').on(t.albumId, t.id),
    check('album_items_size_check', sql`${t.width} > 0 and ${t.height} > 0`),
  ],
);

/**
 * Longest tag name, in UTF-8 bytes: the same limit OxyOS keeps for a tag in a
 * local file's `user.xdg.tags`, so a tag moves between a cloud file and a
 * local one unchanged.
 */
export const FILE_TAG_NAME_MAX_BYTES = 255;

/** Longest asset id kept. Oxy Files ids are far shorter; this only bounds what a client can store. */
export const FILE_TAG_ASSET_ID_MAX_LENGTH = 255;

/**
 * `file_tags` — the person's Finder-style tags on their Oxy Files assets: one
 * row per tag on one asset. Oxy Files has no metadata of its own for this.
 *
 * `asset_id` is an opaque key and is never checked against Oxy Files: a row is
 * only ever read, changed or deleted by its owner (`owner_user_id`, the Oxy
 * user id from the session), so an id that is not theirs only tags nothing.
 * When an asset is deleted for good, the client forgets its rows.
 *
 * Names compare case aside: `name_key` is `lower(name)`, generated by
 * Postgres, so every comparison and the uniqueness below fold case in one
 * place. The spelling a file got first is the one it keeps. `position` is the
 * tag's place in that file's order: a new tag goes after the last, a removal
 * leaves a gap, and nothing ever reorders, so positions only grow.
 *
 * Every write runs in one transaction holding the owner's advisory lock
 * (`file-tags.service.ts`), so one person's changes apply one after another and
 * never race each other's reads of `position` or of who has which name.
 */
export const fileTags = pgTable(
  'file_tags',
  {
    id: generatedId(),
    ownerUserId: text().notNull(),
    assetId: text().notNull(),
    name: text().notNull(),
    nameKey: text()
      .notNull()
      .generatedAlwaysAs((): SQL => sql`lower(${fileTags.name})`),
    position: integer().notNull(),
    createdAt: createdAt(),
  },
  (t) => [
    // A file carries a name once, case aside.
    unique('file_tags_owner_asset_name_key_unique').on(t.ownerUserId, t.assetId, t.nameKey),
    // "The tags of these assets of owner X", already in each file's order.
    unique('file_tags_owner_asset_position_unique').on(t.ownerUserId, t.assetId, t.position),
    // "The assets of owner X tagged N, newest first" (ids are uuidv7, so the id
    // is the cursor), and the person's names grouped by key.
    index('file_tags_owner_name_key_idx').on(t.ownerUserId, t.nameKey, t.id),
    // Trimmed, non-empty, at most the byte limit, and free of `,` and newline:
    // the separators of `user.xdg.tags` and of macOS's tag list.
    check(
      'file_tags_name_check',
      sql`char_length(${t.name}) >= 1
        and octet_length(${t.name}) <= ${sql.raw(String(FILE_TAG_NAME_MAX_BYTES))}
        and btrim(${t.name}, ' ' || chr(9) || chr(13)) = ${t.name}
        and strpos(${t.name}, ',') = 0
        and strpos(${t.name}, chr(10)) = 0`,
    ),
    check(
      'file_tags_asset_id_length_check',
      sql`char_length(${t.assetId}) between 1 and ${sql.raw(String(FILE_TAG_ASSET_ID_MAX_LENGTH))}`,
    ),
    check('file_tags_position_check', sql`${t.position} >= 0`),
  ],
);
